#!/usr/bin/env python3
"""Cross-lingual arms of the downstream experiment, built from the same English seeds and target personas:

  X1  translate only: every seed user turn translated literally into the persona's language by the pipeline's
      persona-blind translation step, no restyle; assistant turns regenerated by the released responder without a
      persona (continuity loop and sanity gate, as A0r; regen.py)
  X2  translate + restyle: the released cross-lingual conversation

Population: released cross-lingual conversations (`setting == cross_lingual`, `match_tier == cross_lingual`) whose
text language is not English, whose persona is not in the 5% held-out set (same rule as build_arms.py) and whose
seed was recovered (seeds.py, cross-lingual setting).

  build      sample --n conversations -> <work>/x1/input/NNN.jsonl (32 shards) + <work>/x1/build_manifest.json
  run        translate + regenerate the given input shards -> <work>/x1/out/<shard>; resumable by id
  assemble   X1 / X2 on the ids that pass in X1 and fit --max-tokens in both arms ->
             <work>/data_x/{X1,X2}_source.jsonl + manifest.json (40,528 conversations in the paper)

  python -m personafactory.downstream.x_arms build --n 50000 --release swiss-ai/PersonaFactory \
      --seeds $PF_OUT_DIR/downstream/seeds_cross_lingual.jsonl --tokenizer $PF_MODEL_DIR/Apertus-v1.5-8B
  python -m personafactory.downstream.x_arms run --gemma $GEMMA_URL --ministral $MINISTRAL_URL --minimax $MINIMAX_URL
  python -m personafactory.downstream.x_arms assemble --tokenizer $PF_MODEL_DIR/Apertus-v1.5-8B
"""
import argparse, asyncio, collections, glob, hashlib, json, os, random, statistics

from personafactory.downstream.common import (HELDOUT_SEED, HF_REPO, MAX_TOKENS, clean, heldout, load_release,
                                              sft_record, sha256_file, token_counter)


def population(release):
    return {r['id']: r for r in load_release(release)
            if r['setting'] == 'cross_lingual' and r['match_tier'] == 'cross_lingual' and not heldout(r['persona_id'])
            and r['language'] not in ('English', 'Unknown', None)}


def build(a, nshards=32):
    rel = population(a.release)
    print('release candidates', len(rel), flush=True)
    seeds = {}
    for line in open(a.seeds, encoding='utf-8'):
        s = json.loads(line)
        if s['id'] in rel:
            seeds[s['id']] = s['conversation']
    ntok = token_counter(a.tokenizer)
    drop, ok = collections.Counter(), []
    for k in sorted(seeds):
        s, x2 = clean(seeds[k]), clean(rel[k]['messages'])
        if s is None or x2 is None:
            drop['malformed'] += 1
        elif len(s) != len(x2):
            drop['turn_mismatch'] += 1
        elif sum(len(m['content']) for m in s) > a.max_chars:
            drop['too_long'] += 1
        elif ntok(x2) > a.max_tokens:
            drop['x2_over_token_cap'] += 1
        else:
            ok.append(k)
    drop['no_seed'] = len(rel) - len(seeds)
    print('eligible', len(ok), dict(drop), flush=True)
    chosen = sorted(random.Random(HELDOUT_SEED + '-x').sample(ok, min(a.n, len(ok))))
    d = os.path.join(a.work, 'x1', 'input')
    os.makedirs(d, exist_ok=True)
    fhs = [open(os.path.join(d, f'{i:03d}.jsonl'), 'w', encoding='utf-8') for i in range(nshards)]
    langs = collections.Counter()
    for k in chosen:
        r = rel[k]
        langs[r['language']] += 1
        fhs[int(hashlib.md5(k.encode()).hexdigest(), 16) % nshards].write(json.dumps({
            'id': k, 'persona_id': r['persona_id'], 'responder': r['responder'], 'lang': r['language'],
            'users': [m['content'] for m in clean(seeds[k]) if m['role'] == 'user']}, ensure_ascii=False) + '\n')
    for f in fhs:
        f.close()
    json.dump({'n': len(chosen), 'eligible': len(ok), 'drops': dict(drop), 'languages': dict(langs.most_common())},
              open(os.path.join(a.work, 'x1', 'build_manifest.json'), 'w'), indent=1)
    print('built', len(chosen), 'languages', len(langs))


def assemble(a):
    rel = population(a.release)
    x1, status, fixed = {}, collections.Counter(), {}
    for fp in glob.glob(os.path.join(a.work, 'x1', 'input', '*.jsonl')):
        for line in open(fp, encoding='utf-8'):
            r = json.loads(line)
            fixed[r['id']] = r
    for fp in glob.glob(os.path.join(a.work, 'x1', 'out', '*.jsonl')):
        for line in open(fp, encoding='utf-8'):
            r = json.loads(line)
            status[r['status']] += 1
            if r['status'] == 'pass':
                c = clean(r['conversation'])
                if c and len(c) == 2 * len(fixed[r['id']]['users']):
                    x1[r['id']] = c
    x2 = {k: clean(rel[k]['messages']) for k in x1 if k in rel}
    ntok = token_counter(a.tokenizer)
    ids = sorted(k for k in x1 if x2.get(k) and len(x2[k]) == len(x1[k]))
    n_common = len(ids)
    ids = [k for k in ids if max(ntok(x1[k]), ntok(x2[k])) <= a.max_tokens]
    out = os.path.join(a.work, 'data_x')
    os.makedirs(out, exist_ok=True)
    man = {'n': len(ids), 'dropped_over_token_cap': n_common - len(ids), 'x1_status': dict(status),
           'median_assistant_chars': {}, 'median_user_chars': {}, 'sha256': {},
           'languages': dict(collections.Counter(rel[k]['language'] for k in ids).most_common())}
    for name, d in (('X1', x1), ('X2', x2)):
        fp = os.path.join(out, f'{name}_source.jsonl')
        with open(fp, 'w', encoding='utf-8') as fh:
            for k in ids:
                fh.write(json.dumps(sft_record(k, rel[k]['language'], d[k]), ensure_ascii=False) + '\n')
        for role in ('assistant', 'user'):
            man[f'median_{role}_chars'][name] = statistics.median(len(m['content']) for k in ids for m in d[k] if m['role'] == role)
        man['sha256'][name] = sha256_file(fp)
    json.dump(man, open(os.path.join(out, 'manifest.json'), 'w'), indent=1)
    print(json.dumps(man, indent=1))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('step', choices=['build', 'run', 'assemble'])
    ap.add_argument('--work', default=os.path.join(os.environ.get('PF_OUT_DIR', './outputs'), 'downstream'))
    ap.add_argument('--release', default=HF_REPO)
    ap.add_argument('--seeds', help='seeds.py output for the cross-lingual setting (build)')
    ap.add_argument('--tokenizer', help='Apertus tokenizer (build, assemble)')
    ap.add_argument('--n', type=int, default=50000, help='conversations to translate and regenerate (build)')
    ap.add_argument('--max-chars', type=int, default=16000, help='seed conversation character cap (build)')
    ap.add_argument('--max-tokens', type=int, default=MAX_TOKENS)
    a, rest = ap.parse_known_args()
    if a.step == 'build':
        build(a)
    elif a.step == 'assemble':
        assemble(a)
    else:
        from personafactory.downstream import regen
        rp = argparse.ArgumentParser()
        regen.add_args(rp)
        r = rp.parse_args(rest)
        asyncio.run(regen.run(r, os.path.join(a.work, 'x1', 'input'), os.path.join(a.work, 'x1', 'out'), translate=True))


if __name__ == '__main__':
    main()
