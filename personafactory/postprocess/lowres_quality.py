REF = {'German': 'LATIN', 'Spanish': 'LATIN'}  # high-resource control languages in the judge sample
LANGS = {**LOWRES, **REF}

JUDGE_PROMPT = """You are a strict native-level reviewer of synthetic chat data in {lang}.

The conversation below was built from an English (or other-language) source conversation. The USER turns were rewritten into {lang} in the voice of a specific persona (casual or idiosyncratic style, typos and dialect are allowed and intended). The ASSISTANT turns were generated by an AI model answering those user turns.

Original first user message (source, for fidelity):
<<<
{source}
>>>

Conversation:
<<<
{conv}
>>>

Rate each item on 1-5 (5 = best) and set flags. Be harsh about language quality: judge as a fluent native speaker of {lang} would.
- user_language: user turns are genuinely {lang} (not another language, not machine-garbled, correct script). 1 = wrong language or gibberish.
- user_fluency: user turns read like something a real {lang} speaker could type (persona style and informality are fine). 1 = unnatural / broken grammar throughout.
- user_fidelity: the first user turn asks for the same thing as the source (same task, constraints, key details). 1 = different request.
- assistant_language: assistant turns are in {lang} (or the language the user explicitly asked for), correct script, no unwarranted switch to English. 1 = wrong language.
- assistant_fluency: assistant {lang} is grammatical and natural. 1 = broken.
- assistant_quality: the assistant answers are helpful, correct and follow the user's instructions. 1 = useless or wrong.
Flags (true/false): code_switching (unnatural mixing with English or another language), mistranslation (meaning visibly changed or lost), stereotype (persona rendered as an ethnic or cultural caricature), repetition (looping or repeated text), truncated (cut off mid-answer).

Answer with ONLY a JSON object:
{{"user_language": n, "user_fluency": n, "user_fidelity": n, "assistant_language": n, "assistant_fluency": n, "assistant_quality": n, "code_switching": b, "mistranslation": b, "stereotype": b, "repetition": b, "truncated": b, "main_issue": "<one short sentence in English, or empty>"}}"""

SCORES = ['user_language', 'user_fluency', 'user_fidelity', 'assistant_language', 'assistant_fluency', 'assistant_quality']
FLAGS = ['code_switching', 'mistranslation', 'stereotype', 'repetition', 'truncated']


def release_lines(release_dir, sub='data'):
    for fp in sorted(glob.glob(os.path.join(release_dir, sub, '*.jsonl'))):
        yield from open(fp, encoding='utf-8')


def lang_of(r):
    """Language of a conversation: the cross-lingual target (LID-normalized), else the detected text language."""
    if r.get('language_mode') == 'multilingual':
        t = r.get('target_language') or r.get('persona_language')
        if t:
            return lid.norm(t)
    return r.get('text_language')


def script_share(text, script):
    """Share of letters whose Unicode name starts with the expected script (None -> None)."""
    if not script:
        return None
    n = hit = 0
    for ch in text:
        if ch.isalpha():
            n += 1
            try:
                hit += unicodedata.name(ch).startswith(script)
            except ValueError:
                pass
    return hit / n if n else None


def rep_score(text):
    """Share of word 3-grams that are repeats (0 = none); high values mean looping."""
    w = text.split()
    g = [tuple(w[i:i + 3]) for i in range(len(w) - 2)]
    return 1 - len(set(g)) / len(g) if len(g) >= 30 else 0.0


def analyse(line):
    r = json.loads(line)
    L = lang_of(r)
    if L not in LANGS:
        return None
    sc = LANGS[L]
    us = [m['content'] for m in r['conversation'] if m['role'] == 'user']
    asst = [m['content'] for m in r['conversation'] if m['role'] == 'assistant']
    ul = [lid.detect(t) for t in us]
    al = [lid.detect(t) for t in asst]
    return {'id': r['id'], 'lang': L, 'part': r['release_part'], 'mode': r['language_mode'], 'responder': r['responder'],
            'source_name': r['source_name'], 'persona_id': r['persona_id'], 'lid_verifiable': r.get('lid_verifiable'),
            'n_turns': len(us),
            'user_lid': ul, 'asst_lid': al,
            'user_script': script_share(' '.join(us), sc), 'asst_script': script_share(' '.join(asst), sc),
            'user_chars': sum(map(len, us)), 'asst_chars': sum(map(len, asst)),
            'len_ratio': len(us[0]) / max(1, len(r.get('source_text') or '')) if us else None,
            'user_rep': max([rep_score(t) for t in us] or [0]), 'asst_rep': max([rep_score(t) for t in asst] or [0]),
            'first_user_sha': hashlib.sha1(re.sub(r'\s+', ' ', us[0].strip().lower()).encode()).hexdigest() if us else None}


def med(x):
    x = sorted(v for v in x if v is not None)
    return x[len(x) // 2] if x else None


def frac(x):
    x = [v for v in x if v is not None]
    return round(sum(x) / len(x), 4) if x else None


def stage_metrics(a):
    os.makedirs(a.out, exist_ok=True)
    rows = []
    with Pool(a.workers, initializer=lid.init, initargs=(a.lid_model,)) as pool:
        for x in pool.imap_unordered(analyse, release_lines(a.release_dir), chunksize=64):
            if x:
                rows.append(x)
    with open(os.path.join(a.out, 'rows.jsonl'), 'w', encoding='utf-8') as f:
        for x in rows:
            f.write(json.dumps(x, ensure_ascii=False) + '\n')
    by = collections.defaultdict(list)
    for x in rows:
        by[x['lang']].append(x)
    persona_use = collections.Counter(x['persona_id'] for x in rows)
    table = {}
    for L, xs in sorted(by.items(), key=lambda kv: -len(kv[1])):
        dup = collections.Counter(x['first_user_sha'] for x in xs)
        lid_ok = lambda lids: [lid.matches(l, L) for l in lids if l != 'TooShort']
        seen_labels = collections.Counter(l for x in xs for l in x['user_lid'] + x['asst_lid'])
        table[L] = {
            'tier': 'ref' if L in REF else 'lowres', 'n': len(xs),
            'by_part': dict(collections.Counter(x['part'] for x in xs)), 'by_mode': dict(collections.Counter(x['mode'] for x in xs)),
            'by_responder': dict(collections.Counter(x['responder'] for x in xs)),
            'lid_detectable': seen_labels[L] > 0,  # False: neither detector can label L, the LID match is meaningless
            'user_lid_match': frac([v for x in xs for v in lid_ok(x['user_lid'])]),
            'asst_lid_match': frac([v for x in xs for v in lid_ok(x['asst_lid'])]),
            'user_english_turn_share': frac([l == 'English' for x in xs for l in x['user_lid']]),
            'asst_english_turn_share': frac([l == 'English' for x in xs for l in x['asst_lid']]),
            'user_lid_top': collections.Counter(l for x in xs for l in x['user_lid']).most_common(4),
            'asst_lid_top': collections.Counter(l for x in xs for l in x['asst_lid']).most_common(4),
            'user_script_med': med([x['user_script'] for x in xs]), 'asst_script_med': med([x['asst_script'] for x in xs]),
            'user_script_low_share': frac([x['user_script'] < .5 for x in xs if x['user_script'] is not None]),
            'asst_script_low_share': frac([x['asst_script'] < .5 for x in xs if x['asst_script'] is not None]),
            'len_ratio_med': med([x['len_ratio'] for x in xs]),
            'len_ratio_lt_0.3_share': frac([x['len_ratio'] < .3 for x in xs if x['len_ratio'] is not None]),
            'user_rep_gt_0.3_share': frac([x['user_rep'] > .3 for x in xs]), 'asst_rep_gt_0.3_share': frac([x['asst_rep'] > .3 for x in xs]),
            'asst_chars_med': med([x['asst_chars'] for x in xs]), 'mean_turns': round(sum(x['n_turns'] for x in xs) / len(xs), 2),
            'dup_first_user_share': round(sum(c - 1 for c in dup.values()) / len(xs), 4),
            'distinct_personas': len({x['persona_id'] for x in xs}),
            'max_persona_reuse': max(persona_use[x['persona_id']] for x in xs),
        }
    json.dump({'langs': table, 'n_rows': len(rows)}, open(os.path.join(a.out, 'metrics.json'), 'w'), indent=1, ensure_ascii=False)
    # judge sample: N per language, round robin over part x responder strata, deterministic
    rnd = random.Random(20261031)
    keep = {}
    for L, xs in by.items():
        if len(xs) < a.min_n:
            continue
        strata = collections.defaultdict(list)
        for x in sorted(xs, key=lambda x: x['id']):
            strata[(x['part'], x['responder'])].append(x['id'])
        for s in strata.values():
            rnd.shuffle(s)
        pick, ks = [], sorted(strata)
        while len(pick) < min(a.n, len(xs)):
            for k in ks:
                if strata[k] and len(pick) < a.n:
                    pick.append(strata[k].pop())
        for i in pick:
            keep[i] = L
    with open(os.path.join(a.out, 'sample.jsonl'), 'w', encoding='utf-8') as f:
        for l in release_lines(a.release_dir):
            r = json.loads(l)
            if r['id'] in keep:
                r['_lang'] = keep[r['id']]
                f.write(json.dumps(r, ensure_ascii=False) + '\n')
    print(json.dumps({L: (v['n'], v['user_lid_match'], v['asst_lid_match']) for L, v in table.items()}, indent=0, ensure_ascii=False))
    print('sample', len(keep))


class Bucket:
    """Global request-rate limit shared by the judge threads."""
    def __init__(self, rpm):
        self.gap, self.lock, self.t = 60.0 / rpm, threading.Lock(), 0.0

    def wait(self):
        with self.lock:
            now = time.monotonic()
            self.t = max(self.t + self.gap, now)
            d = self.t - now
        time.sleep(d)


def call(url, model, prompt, bucket, key):
    import requests
    for attempt in range(8):
        bucket.wait()
        try:
            r = requests.post(url, headers={'Authorization': f'Bearer {key}'}, timeout=300,
                              json={'model': model, 'messages': [{'role': 'user', 'content': prompt}],
                                    'temperature': 0.0, 'max_tokens': 8192})
        except Exception:
            time.sleep(10)
            continue
        if r.status_code == 429:
            m = re.search(r'(\d+) seconds', r.text)
            time.sleep(int(m.group(1)) + 1 if m else 30)
            continue
        if r.status_code != 200:
            time.sleep(10)
            continue
        txt = r.json()['choices'][0]['message'].get('content') or ''
        m = re.search(r'\{.*\}', txt, re.S)
        if not m:
            continue
        try:
            return json.loads(m.group(0))
        except ValueError:
            continue
    return None


def render(r):
    return '\n\n'.join(f"[{m['role'].upper()}]\n{m['content'][:6000]}" for m in r['conversation'])


def stage_judge(a):
    if not a.judge_url:
        raise SystemExit('--judge-url (or PF_JUDGE_URL) is required for the judge stage')
    url = a.judge_url.rstrip('/')
    url = url if url.endswith('/chat/completions') else url + '/chat/completions'
    key = os.environ.get('PF_API_KEY', 'dummy')
    fo_path = os.path.join(a.out, f'judge_{a.tag}.jsonl')
    done = set()
    if os.path.exists(fo_path):
        for l in open(fo_path, encoding='utf-8'):
            try:
                done.add(json.loads(l)['id'])
            except ValueError:
                pass
    todo = [json.loads(l) for l in open(os.path.join(a.out, 'sample.jsonl'), encoding='utf-8')]
    todo = [r for r in todo if r['id'] not in done]
    print(a.tag, 'todo', len(todo), flush=True)
    bucket, lock = Bucket(a.rpm), threading.Lock()
    fo = open(fo_path, 'a', encoding='utf-8')
    from concurrent.futures import ThreadPoolExecutor

    def one(r):
        p = JUDGE_PROMPT.format(lang=r['_lang'], source=(r.get('source_text') or '')[:4000], conv=render(r))
        v = call(url, a.model, p, bucket, key)
        with lock:
            fo.write(json.dumps({'id': r['id'], 'lang': r['_lang'], 'part': r['release_part'], 'responder': r['responder'],
                                 'mode': r['language_mode'], 'source_name': r['source_name'], 'judge': a.model, 'verdict': v},
                                ensure_ascii=False) + '\n')
            fo.flush()
    with ThreadPoolExecutor(a.threads) as ex:
        list(ex.map(one, todo))
    fo.close()


def agg(vs):
    vs = [v for v in vs if isinstance(v, dict)]
    out = {'n': len(vs)}
    for s in SCORES:
        x = [v.get(s) for v in vs if isinstance(v.get(s), (int, float))]
        out[s] = round(sum(x) / len(x), 2) if x else None
    for f in FLAGS:
        x = [v.get(f) for v in vs if isinstance(v.get(f), bool)]
        out[f] = round(sum(x) / len(x), 3) if x else None
    return out


def stage_report(a):
    met = json.load(open(os.path.join(a.out, 'metrics.json')))['langs']
    rep = {'metrics': met, 'judges': {}}
    for fp in sorted(glob.glob(os.path.join(a.out, 'judge_*.jsonl'))):
        tag = os.path.basename(fp)[6:-6]
        rows = [json.loads(l) for l in open(fp, encoding='utf-8')]
        g = collections.defaultdict(list)
        for x in rows:
            g[('lang', x['lang'])].append(x['verdict'])
            tier = 'ref' if x['lang'] in REF else 'lowres'
            g[('tier', tier)].append(x['verdict'])
            g[('tier_part', f"{tier}/{x['part']}")].append(x['verdict'])
            g[('tier_responder', f"{tier}/{x['responder']}")].append(x['verdict'])
        rep['judges'][tag] = {'failed_calls': sum(x['verdict'] is None for x in rows),
                              **{f'{k}:{v}': agg(vs) for (k, v), vs in sorted(g.items())},
                              'issues': collections.Counter(x['lang'] for x in rows if isinstance(x['verdict'], dict) and x['verdict'].get('main_issue')).most_common()}
    tags = sorted(rep['judges'])
    if len(tags) == 2:  # agreement between two judges on the same ids: mean absolute difference per score
        A = {json.loads(l)['id']: json.loads(l)['verdict'] for l in open(os.path.join(a.out, f'judge_{tags[0]}.jsonl'), encoding='utf-8')}
        Bv = {json.loads(l)['id']: json.loads(l)['verdict'] for l in open(os.path.join(a.out, f'judge_{tags[1]}.jsonl'), encoding='utf-8')}
        both = [i for i in A if isinstance(A[i], dict) and isinstance(Bv.get(i), dict)]
        rep['agreement'] = {'n': len(both), **{s: round(sum(abs((A[i].get(s) or 0) - (Bv[i].get(s) or 0)) for i in both) / max(1, len(both)), 2) for s in SCORES}}
    json.dump(rep, open(os.path.join(a.out, 'report.json'), 'w'), indent=1, ensure_ascii=False)
    print(json.dumps({t: {k: v for k, v in j.items() if k.startswith('tier')} for t, j in rep['judges'].items()}, indent=1))


def main():
    env = os.environ.get
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--stage', choices=('metrics', 'judge', 'report'), required=True)
    ap.add_argument('--release-dir', help='merged release directory (metrics stage)')
    ap.add_argument('--out', default=os.path.join(env('PF_OUT_DIR', './outputs'), 'lowres_quality'))
    ap.add_argument('--lid-model', default=env('PF_LID_MODEL'))
    ap.add_argument('--workers', type=int, default=128)
    ap.add_argument('--n', type=int, default=20, help='judge sample size per language')
    ap.add_argument('--min-n', type=int, default=30, help='languages with fewer conversations are not sampled')
    ap.add_argument('--judge-url', default=env('PF_JUDGE_URL'), help='OpenAI-compatible base URL (.../v1) of the judge')
    ap.add_argument('--model', default='deepseek-ai/DeepSeek-V4.1-Flash', help='judge model name as served')
    ap.add_argument('--tag', default='dsv41flash', help='judge output tag: judge_<tag>.jsonl')
    ap.add_argument('--rpm', type=float, default=13, help='global request rate limit (requests per minute)')
    ap.add_argument('--threads', type=int, default=16)
    a = ap.parse_args()
    {'metrics': stage_metrics, 'judge': stage_judge, 'report': stage_report}[a.stage](a)


if __name__ == '__main__':
    main()
