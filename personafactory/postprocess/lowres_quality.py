#!/usr/bin/env python3
"""Low-resource language quality analysis of a merged release directory (release.merge_release output).

  --stage metrics  every conversation whose language (multilingual target, else LID of the text) is in LOWRES or REF:
                   per-turn LID of user and assistant turns, expected-script share, English leakage, user/source
                   length ratio, 3-gram repetition, duplicate first user turns. Writes <out>/rows.jsonl (one row per
                   conversation, the input of apply_lowres_filter / drop_lowscript), the per-language table
                   <out>/metrics.json and the judge sample <out>/sample.jsonl (--n per language, round robin over
                   part x responder strata, seed 20261031).
  --stage judge    LLM judge of <out>/sample.jsonl against an OpenAI-compatible chat endpoint with a global request
                   rate limit -> <out>/judge_<tag>.jsonl (resumable by id). Any sample file with the same fields can be
                   judged with --out pointing at its directory (postprocess.judge_lowres_regen, asst_regen_judge).
  --stage report   <out>/report.json from metrics and every judge_*.jsonl (per language / tier / part / responder;
                   agreement when two judges are present).

  python -m personafactory.postprocess.lowres_quality --stage metrics --release-dir ./release_merged --out ./outputs/lowres_quality
  python -m personafactory.postprocess.lowres_quality --stage judge --out ./outputs/lowres_quality \\
      --judge-url $JUDGE_URL --model deepseek-ai/DeepSeek-V4.1-Flash --tag dsv41flash --rpm 13 --threads 16
  python -m personafactory.postprocess.lowres_quality --stage report --out ./outputs/lowres_quality
"""
